# src/incident_copilot/rag/ingest.py. Modifications: adapted to the
# runbook_chunks schema — deterministic chunk_id
# `rb:{doc_slug}:{section_slug}:{sha256(content)[:8]}`, idempotent upsert via
# ON CONFLICT (chunk_id) DO UPDATE (content/embedding/updated_at recomputed on
# re-ingest), service_id/env columns, no structlog, no pgvector package. See
# ATTRIBUTION.md and third_party/incident-copilot/.
"""Ingestion pipeline: runbooks -> chunks -> embeddings -> runbook_chunks.

Idempotent: re-running re-upserts every chunk under its deterministic
chunk_id and recomputes content, embedding and updated_at, so edits to a
runbook propagate without leaving stale rows behind.

Column mapping against migrations/002_runbooks.sql:
    chunk_id      <- rb:{doc_slug}:{section_slug}:{sha256(content)[:8]}
    doc_path      <- corpus-root-relative path of the .md file
    section_path  <- the chunker's heading breadcrumb
    service_id    <- leading token of the file stem ("s3-access-denied.md" -> "s3")
    env           <- caller-supplied environment tag (settings.environment)
    content       <- chunk body; tsv is generated by the schema, never inserted
    embedding     <- embedder output as text, cast ::vector (no pgvector package)
"""

from __future__ import annotations

import hashlib
import re
from pathlib import Path

import psycopg
from pydantic import BaseModel

from .chunker import chunk_markdown
from .embeddings import Embedder, format_vector

UPSERT_SQL = """
INSERT INTO runbook_chunks
    (chunk_id, doc_path, section_path, service_id, env, content, embedding,
     updated_at)
VALUES (%s, %s, %s, %s, %s, %s, %s::vector, now())
ON CONFLICT (chunk_id) DO UPDATE SET
    doc_path = EXCLUDED.doc_path,
    section_path = EXCLUDED.section_path,
    service_id = EXCLUDED.service_id,
    env = EXCLUDED.env,
    content = EXCLUDED.content,
    embedding = EXCLUDED.embedding,
    updated_at = now()
"""

_SLUG_RE = re.compile(r"[^a-z0-9]+")
_SLUG_MAX = 60


def _slug(text: str) -> str:
    """Lowercase slug: non-alphanum runs become '-', capped for readability."""
    slug = _SLUG_RE.sub("-", text.lower()).strip("-")
    return slug[:_SLUG_MAX].rstrip("-")


def chunk_id_for(doc_slug: str, heading_path: str, content: str) -> str:
    """Deterministic chunk id: `rb:{doc_slug}:{section_slug}:{sha256[:8]}`.

    The content hash makes the id change exactly when the chunk text changes;
    the doc and section slugs keep ids human-greppable.
    """
    digest = hashlib.sha256(content.encode("utf-8")).hexdigest()[:8]
    return f"rb:{doc_slug}:{_slug(heading_path)}:{digest}"


class IngestStats(BaseModel):
    """One ingestion run, in counts (the CLI prints these verbatim)."""

    files: int
    chunks_seen: int
    chunks_upserted: int


class RunbookIngestor:
    """Upserts a runbook corpus into runbook_chunks.

    `doc_path` is built from the corpus root you pass plus the file name —
    pass a relative root (e.g. settings.runbook_dir = "runbooks") to get
    repo-relative values like "runbooks/s3-access-denied.md".
    """

    def __init__(self, conn: psycopg.Connection, embedder: Embedder, env: str = "dev") -> None:
        self._conn = conn
        self._embedder = embedder
        self._env = env

    def ingest_dir(self, path: str | Path) -> IngestStats:
        root = Path(path)
        doc_base = root.as_posix().rstrip("/")
        files = sorted(root.glob("*.md"))
        seen = 0
        upserted = 0
        try:
            with self._conn.cursor() as cur:
                for f in files:
                    doc_slug = f.stem
                    chunks = chunk_markdown(f.read_text(encoding="utf-8"), doc_slug)
                    vectors = self._embedder.embed([c.content for c in chunks])
                    for c, vector in zip(chunks, vectors, strict=True):
                        seen += 1
                        cur.execute(
                            UPSERT_SQL,
                            (
                                chunk_id_for(doc_slug, c.heading_path, c.content),
                                f"{doc_base}/{f.name}",
                                c.heading_path,
                                doc_slug.split("-", 1)[0],
                                self._env,
                                c.content,
                                format_vector(vector),
                            ),
                        )
                        upserted += cur.rowcount
            self._conn.commit()
        except Exception:
            self._conn.rollback()
            raise
        return IngestStats(files=len(files), chunks_seen=seen, chunks_upserted=upserted)
